/* Generates features/landing/home/lib/landfine.ts from Natural Earth 1:50m land (public domain, naturalearthdata.com).
   Usage: node scripts/gen-landfine.mjs path/to/ne_50m_land.geojson
   Exterior rings only, Douglas-Peucker 0.025 degrees, quantised to 0.01 degrees, delta-encoded "dlon,dlat" in 1/100 degree.
   Islands whose box is under 0.2 degrees are dropped. Used only by the shipment map (zoomed views); the hero map keeps lib/landdata.ts. */
import { readFileSync, writeFileSync } from "node:fs";

const TOL = 0.025;
const src = JSON.parse(readFileSync(process.argv[2], "utf8"));

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let dmax = 0, im = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-12;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs((pts[i][0] - ax) * dy - (pts[i][1] - ay) * dx) / len;
      if (d > dmax) { dmax = d; im = i; }
    }
    if (dmax > tol) { keep[im] = 1; stack.push([a, im], [im, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const rings = [];
for (const f of src.features) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const poly of polys) {
    const ring = poly[0];
    const xs = ring.map((p) => p[0]), ys = ring.map((p) => p[1]);
    if (Math.max(...xs) - Math.min(...xs) < 0.2 && Math.max(...ys) - Math.min(...ys) < 0.2) continue;
    const h = Math.floor(ring.length / 2);   // a closed ring has the same first and last point: simplify its two halves
    const s = [...dp(ring.slice(0, h + 1), TOL).slice(0, -1), ...dp(ring.slice(h), TOL)].map(([x, y]) => [Math.round(x * 100), Math.round(y * 100)]);
    const d = s.filter((p, i) => i === 0 || p[0] !== s[i - 1][0] || p[1] !== s[i - 1][1]);
    if (d.length >= 4) rings.push(d);
  }
}
const enc = rings.map((r) => { let x = 0, y = 0; return r.map(([a, b]) => { const s = `${a - x},${b - y}`; x = a; y = b; return s; }).join(" "); });
const out = `/* Natural Earth 1:50m land (public domain), exterior rings, simplified (Douglas-Peucker, ${TOL} degrees) and quantised to 0.01 degrees; delta-encoded rings of "dlon,dlat" in 1/100 degree.
   Generated by scripts/gen-landfine.mjs; see LICENSES.md. Used by the shipment map only. */
const RINGS: string[] = ${JSON.stringify(enc)};
export function fineRings(): [number, number][][] {
  return RINGS.map((s) => { let x = 0, y = 0; return s.split(" ").map((p) => { const [a, b] = p.split(",").map(Number); x += a!; y += b!; return [x / 100, y / 100] as [number, number]; }); });
}
`;
writeFileSync("features/landing/home/lib/landfine.ts", out);
console.log(rings.length, "rings,", rings.reduce((a, r) => a + r.length, 0), "points,", Math.round(out.length / 1024), "KB");
